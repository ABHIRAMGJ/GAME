export function getTierFromRating(rating: number): { tier: RatingTier; color: string; bg: string } {
  if (rating >= 2000) return { tier: 'Master', color: 'text-amber-400', bg: 'bg-amber-400/10 border-amber-400/30' };
  if (rating >= 1800) return { tier: 'Diamond', color: 'text-cyan-400', bg: 'bg-cyan-400/10 border-cyan-400/30' };
  if (rating >= 1600) return { tier: 'Platinum', color: 'text-emerald-400', bg: 'bg-emerald-400/10 border-emerald-400/30' };
  if (rating >= 1400) return { tier: 'Gold', color: 'text-yellow-400', bg: 'bg-yellow-400/10 border-yellow-400/30' };
  if (rating >= 1200) return { tier: 'Silver', color: 'text-slate-300', bg: 'bg-slate-300/10 border-slate-300/30' };
  return { tier: 'Bronze', color: 'text-orange-400', bg: 'bg-orange-400/10 border-orange-400/30' };
}

export function getLevelProgress(xp: number): { level: number; currentLevelXp: number; nextLevelXp: number; progressPercent: number } {
  // Level curve: Level 1 = 0 XP, Level 2 = 500, Level 3 = 1200, etc.
  const level = Math.max(1, Math.floor(Math.sqrt(xp / 100)) + 1);
  const currentBase = Math.pow(level - 1, 2) * 100;
  const nextBase = Math.pow(level, 2) * 100;
  const currentLevelXp = Math.max(0, xp - currentBase);
  const nextLevelXp = nextBase - currentBase;
  const progressPercent = Math.min(100, Math.max(0, Math.round((currentLevelXp / nextLevelXp) * 100)));

  return { level, currentLevelXp, nextLevelXp, progressPercent };
}
